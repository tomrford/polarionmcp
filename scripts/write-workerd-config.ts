import { readdir, readFile, writeFile } from "node:fs/promises";

// wrangler.jsonc is plain JSON (no comments), so it can be the single source for these settings.
const wrangler = JSON.parse(await readFile("wrangler.jsonc", "utf8")) as {
  compatibility_date: string;
  compatibility_flags: string[];
  vars: Record<string, string>;
};
const bindings = Object.keys(wrangler.vars)
  .map((name) => `    (name = "${name}", fromEnvironment = "${name}"),`)
  .join("\n");

const wasmModules = (await readdir("dist"))
  .filter((name) => name.endsWith(".wasm"))
  .sort()
  .map((name) => `    (name = "./${name}", wasm = embed "${name}"),`)
  .join("\n");

if (!wasmModules) {
  throw new Error("dist/ has no .wasm modules; wrangler must emit jSquash codecs");
}

const capnp = `# Generated by scripts/write-workerd-config.ts. Do not edit by hand.
using Workerd = import "/workerd/workerd.capnp";

const config :Workerd.Config = (
  services = [
    (name = "main", worker = .mainWorker),
    (name = "internet",
      network = (
        allow = ["public", "private"],
        tlsOptions = (trustBrowserCas = true)
      )
    ),
  ],
  sockets = [
    (name = "http", address = "*:8080", http = (), service = "main"),
  ],
);

const mainWorker :Workerd.Worker = (
  modules = [
    (name = "index.js", esModule = embed "index.js"),
${wasmModules}
  ],
  compatibilityDate = "${wrangler.compatibility_date}",
  compatibilityFlags = ${JSON.stringify(wrangler.compatibility_flags)},
  globalOutbound = "internet",
  bindings = [
${bindings}
    (name = "LOADER", workerLoader = ()),
  ],
);
`;

await writeFile("dist/config.capnp", capnp);
